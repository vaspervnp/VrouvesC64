# ------------------------------------------------------------------ title pictures
def pens_to_colours(rows):
    return [[g.PEN2C[p] for p in r] for r in rows]


def title_art():
    """the first title page, lines 40-167 (rows 5-20), as C64 cells, packed"""
    world.TART_ROWS = (104, 120, 136, 152)      # the labels on character rows 13-19
    cv = world.title_art()
    img = pens_to_colours(cv.p)
    bmp, scr, col, shown = g.quantize(img)
    g.save_png(shown, os.path.join(PREVIEW, "title_art.png"))
    out = ["; the first title page: rows 5-20, its bitmap, screen and colour RAM, each packed (lz.asm)"]
    total = 0
    for nm, part in (("bmp", bmp), ("scr", scr), ("col", col)):
        packed = lz.pack(part)
        total += len(packed)
        out += ["title_art_%s" % nm] + db(list(packed))
    print("title art: %d cells, %d bytes packed" % (len(scr), total))
    return out


def icons():
    """the defenders' and invaders' pictures on the title pages: 3 x 2 cells,
    a patch of grass with the figure, bitmap (48), screen (6), colour (6)"""
    G = ["; title page pictures: 3 x 2 cells each: bitmap 48, screen 6, colour 6"]
    figs = [art.CRETAN, art.YIAYIA, art.BRIDE, art.PSSSST, art.CAULDRON, art.BAKER,
            art.DRONE_A, art.GUARD_A, art.TANK_V_A]
    G.append("icons")
    for rows in figs:
        cv = world.Canvas(12, 16, art.CH['k'])
        cv.rect(0, 1, 11, 14, art.CH['g'])
        cv.blit(rows, 2, 2)
        img = pens_to_colours(cv.p)
        bmp, scr, col, _ = g.quantize(img)
        # quantize() gives the cells row by row; keep that order
        G += db(bmp + scr + col, 20)
    return G


def load_rgb(path, w, h, enhance=None):
    im = Image.open(path).convert("RGB")
    if enhance:
        im = enhance(im)
    return im.resize((w, h), Image.LANCZOS if im.size[0] > w * 2 else Image.NEAREST)


def picture(im, name, dither=0.5, title=None):
    """an RGB picture (160 x 200) -> a multicolour bitmap: the background
    picked for the least error, three colours per cell picked greedily, then
    dithered inside the cell's colours.  -> (bg, bitmap, screen, colour)"""
    W, H = 160, 200
    px = [[list(im.getpixel((x, y))) for x in range(W)] for y in range(H)]
    if title:
        title(px)
    rgb = pal.RGB
    wt = (3, 4, 2)

    def d2(a, b):
        return sum(w_ * (x - y) ** 2 for w_, x, y in zip(wt, a, b))
    near = [[min(range(16), key=lambda c: d2(p, rgb[c])) for p in row] for row in px]
    best = None
    for bg in range(16):
        err = 0
        for cy in range(25):
            for cx in range(40):
                cnt = {}
                for y in range(8):
                    for x in range(4):
                        c = near[cy * 8 + y][cx * 4 + x]
                        cnt[c] = cnt.get(c, 0) + 1
                cnt.pop(bg, None)
                err += sum(sorted(cnt.values())[:-3]) if len(cnt) > 3 else 0
        if best is None or err < best[0]:
            best = (err, bg)
    bg = best[1]
    out = [[0] * W for _ in range(H)]
    bmp, scr, col = [], [], []
    cellcols = {}
    for cy in range(25):
        for cx in range(40):
            cells = [px[cy * 8 + y][cx * 4 + x] for y in range(8) for x in range(4)]
            chosen = [bg]
            for _ in range(3):
                top = None
                for c in range(16):
                    if c in chosen:
                        continue
                    e = sum(min(d2(p, rgb[s]) for s in chosen + [c]) for p in cells)
                    if top is None or e < top[0]:
                        top = (e, c)
                chosen.append(top[1])
            cellcols[(cx, cy)] = chosen
    # dither (Floyd-Steinberg, part of the error), each pixel to its cell's colours
    buf = [[list(map(float, p)) for p in row] for row in px]
    for y in range(H):
        for x in range(W):
            cs = cellcols[(x // 4, y // 8)]
            c = [min(255.0, max(0.0, v)) for v in buf[y][x]]
            k = min(cs, key=lambda s: d2(c, rgb[s]))
            out[y][x] = k
            e = [(c[i] - rgb[k][i]) * dither for i in range(3)]
            for dx, dy, f in ((1, 0, 7), (-1, 1, 3), (0, 1, 5), (1, 1, 1)):
                if 0 <= x + dx < W and y + dy < H:
                    for i in range(3):
                        buf[y + dy][x + dx][i] += e[i] * f / 16
    for cy in range(25):
        for cx in range(40):
            cs = cellcols[(cx, cy)]
            for y in range(8):
                b = 0
                for x in range(4):
                    b = b << 2 | cs.index(out[cy * 8 + y][cx * 4 + x])
                bmp.append(b)
            scr.append(cs[1] << 4 | cs[2])
            col.append(cs[3])
    g.save_png(out, os.path.join(PREVIEW, name + ".png"))
    return bg, bmp, scr, col


def title_on(px, text, y0, colour, shadow):
    """big letters (the game's font, twice as big) centred on row y0"""
    w = len(text) * 8
    x0 = (160 - w) // 2
    for k, ch in enumerate(text):
        rows = font.glyph_rows(font.glyph_index(ch))
        for j, bits in enumerate(rows):
            for i in range(3):
                if bits & (4 >> i):
                    for yy in range(2):
                        for xx in range(2):
                            for (ox, oy, c) in ((1, 1, shadow), (0, 0, colour)):
                                X = x0 + k * 8 + i * 2 + xx + ox
                                Y = y0 + j * 2 + yy + oy
                                if 0 <= X < 160 and 0 <= Y < 200:
                                    px[Y][X] = list(pal.RGB[c])


def splash():
    def bold(im):
        im = ImageEnhance.Color(im).enhance(1.4)
        return ImageEnhance.Contrast(im).enhance(1.1)
    im = load_rgb(os.path.join(ROOT, "assets", "vrouves.jpeg"), 160, 200, bold)
    bg, bmp, scr, col = picture(im, "splash", 0.45,
                                lambda px: title_on(px, "LET'S GO FOR VROUVES", 6, g.WHITE, g.BLACK))
    # splash.bin, loaded at $4000 by the boot program: bitmap, screen, colour, bg
    open(os.path.join(BUILD, "splash.bin"), "wb").write(bytes(bmp + scr + col + [bg]))
    return bg


def ending():
    def bold(im):
        im = ImageEnhance.Color(im).enhance(1.3)
        return ImageEnhance.Contrast(im).enhance(1.1)
    # the Blender render (tools/ending_blender.py), not the CPC's dithered screen
    im = load_rgb(os.path.join(ROOT, "assets", "ending_scene.png"), 160, 200, bold)
    bg, bmp, scr, col = picture(im, "ending", 0.45)
    # VR-ENDSCR for $c000: screen, colour, background; VR-ENDBMP for $e000: the
    # bitmap (with their load addresses, as files on the disk)
    open(os.path.join(BUILD, "endscr.prg"), "wb").write(bytes([0x00, 0xC0] + scr + col + [bg]))
    open(os.path.join(BUILD, "endbmp.prg"), "wb").write(bytes([0x00, 0xE0] + bmp))


def previews(built):
    for k, b in enumerate(built):
        cv = world.render_background(world.STAGES[k], b["grid"], True)
        img = pens_to_colours(cv.p)
        _, _, _, shown = g.quantize(img)
        g.save_png(shown, os.path.join(PREVIEW, "stage%d.png" % (k + 1)))


