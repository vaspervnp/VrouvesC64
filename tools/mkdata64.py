def db(data, per=16):
    return ["        .byte " + ",".join("$%02x" % (v & 255) for v in data[i:i + per])
            for i in range(0, len(data), per)]


def nib_bytes(rows):
    """rows of pens (or None: clear = pen 0) -> two pens a byte, left high"""
    out = []
    for r in rows:
        for x in range(0, len(r), 2):
            out.append((r[x] << 4) | r[x + 1])
    return out


def art_pens(rows):
    """art rows -> pens; '.' = 0 (clear), black = 15 ('k' and 'n')"""
    return [[0 if ch == '.' else 15 if ch in 'kn' else art.CH[ch] for ch in r] for r in rows]


# ------------------------------------------------------------------ tables
def tables():
    A = ["; generated by tools/mkdata64.py - do not edit", ""]
    A.append("BG_COLOUR = %d" % g.BG)
    A.append("SPR_MC0 = %d" % g.SPR_MC0)
    A.append("SPR_MC1 = %d" % g.SPR_MC1)
    A.append("; CPC pen -> C64 colour")
    A.append("pen_colour")
    A += db(g.PEN2C)
    # two pens a byte -> the colour of each; $ff: clear (pen 0, overlays)
    A.append("hi_colour")
    A += db([g.PEN2C[b >> 4] for b in range(256)])
    A.append("lo_colour")
    A += db([g.PEN2C[b & 15] for b in range(256)])
    A.append("hi_colour_t")
    A += db([0xFF if b >> 4 == 0 else g.PEN2C[b >> 4] for b in range(256)])
    A.append("lo_colour_t")
    A += db([0xFF if b & 15 == 0 else g.PEN2C[b & 15] for b in range(256)])
    A.append("; how far two colours look apart: [a*16+b]")
    A.append("dist_tab")
    A += db([g.DIST[a][b] for a in range(16) for b in range(16)])
    A.append("; how bright: for the shots, drawn in the brightest colour of a cell")
    A.append("; text: 3 bits of a letter's row (bit 2 the left pixel) -> a bitmap byte,")
    A.append("; %01 the letter, %10 behind it; twice as wide: the left cell, the right")
    pat = lambda b, i: 1 if b & (4 >> i) else 2
    A.append("glyph_pat")
    A += db([pat(b, 0) << 6 | pat(b, 1) << 4 | pat(b, 2) << 2 | 2 for b in range(8)])
    A.append("big_l")
    A += db([pat(b, 0) * 0x50 | pat(b, 1) * 0x05 for b in range(8)])
    A.append("big_r")
    A += db([pat(b, 2) * 0x50 | 0x0a for b in range(8)])
    A.append("; a playfield line -> its tile row, its line in the tile * 4")
    A.append("div12")
    A += db([y // 12 for y in range(168)])
    A.append("mod12x4")
    A += db([(y % 12) * 4 for y in range(168)])
    A.append("luma_tab")
    A += db([int(g.luma(c)) for c in range(16)])
    return A


# ------------------------------------------------------------------ font
def font_data():
    A = ["; the 3x6 font: per glyph 6 rows of 3 bits (bit 2 the left pixel)"]
    A.append("NUM_GLYPHS = %d" % len(font.GLYPHS))
    for nm, ch in (("SPACE", " "), ("SLASH", "/"), ("0", "0"), ("PLUS", "+"), ("MINUS", "-"),
                   ("PCT", "%"), ("2", "2"), ("5", "5")):
        A.append("G_%s = %d" % (nm, font.glyph_index(ch)))
    A.append("font")
    d = []
    for i in range(len(font.GLYPHS)):
        d += font.glyph_rows(i)
    A += db(d, 12)
    return A


# ------------------------------------------------------------------ stages
def stage_data():
    """-> (gfx lines, stage lines, built info)"""
    tiles, tile_list = {}, []

    def tid(tb):
        if tb not in tiles:
            tiles[tb] = len(tile_list)
            tile_list.append(tb)
        return tiles[tb]

    def cell_pens(cv, c, r):
        rows = [cv.p[r * 12 + y][c * 8:c * 8 + 8] for y in range(12)]
        return tuple(nib_bytes(rows))

    built = []
    for k, st in enumerate(world.STAGES):
        grid = world.carve_path(st.map, st.ground)
        full = world.render_background(st, grid, True)
        empty = world.render_background(st, grid, False)
        local, lmap, tmap, cmap = {}, [], [], []

        def lid(tb):
            gi = tid(tb)
            if gi not in local:
                local[gi] = len(lmap)
                lmap.append(gi)
            return local[gi]
        for r in range(world.MH):
            for c in range(world.MW):
                tmap.append(lid(cell_pens(full, c, r)))
                t = grid[r][c]
                cmap.append(0 if t in '.F' else 1 if t == '#' else 3 if t in 'KP' else 2)
        sacks = []
        for (c, r) in st.sacks:
            f = tmap[r * world.MW + c]
            e = lid(cell_pens(empty, c, r))
            assert f != e
            sacks += [c, r, f, e]
        paths = []
        for wps in (st.ground, st.air):
            segs = []
            for (a_, b_) in zip(wps, wps[1:]):
                (c0, r0), (c1, r1) = a_, b_
                dc, dr = c1 - c0, r1 - r0
                assert dc == 0 or dr == 0 or abs(dc) == abs(dr)
                n = 12 * max(abs(dc), abs(dr))
                assert n < 256
                segs.append(((dc > 0) - (dc < 0), (dr > 0) - (dr < 0), n))
            c0, r0 = wps[0]
            x0, y0, sub0, rem0 = c0 * 4, r0 * 12, 0, segs[0][2]
            while y0 < 2:
                dx, dy, _ = segs[0]
                y0 += dy
                sub0 += 1
                if sub0 == 3:
                    sub0 = 0
                    x0 += dx
                rem0 -= 1
            data = [x0, y0, sub0, rem0]
            for (dx, dy, n) in segs:
                data += [dx & 0xFF, dy & 0xFF, n]
            paths.append(data + [0, 0, 0])
        waves = getattr(world, st.waves)
        built.append(dict(tmap=tmap, cmap=cmap, lmap=lmap, sacks=sacks, flag=st.flag,
                          pg=paths[0], pa=paths[1], waves=waves, grid=grid, full=full))
        print("stage %d: %d tiles" % (k + 1, len(lmap)))
    print("all stages: %d tiles, %d bytes" % (len(tile_list), 48 * len(tile_list)))
    G = ["; the tiles of every stage: 8 x 12 pixels, CPC pens two a byte", "tiles"]
    for tb in tile_list:
        G += db(tb, 24)
    G.append("NUM_TILES = %d" % len(tile_list))
    return G, built


def unlocks(ids):
    out = []
    for k in range(len(world.STAGES)):
        if k < len(world.UNLOCKS):
            types, l1, l2 = world.UNLOCKS[k]
            ann = [ids.index(l1), ids.index(l2)]
        else:
            types, ann = {1, 2, 3, 4, 5, 6}, [0xFF, 0xFF]
        out.append([sum(1 << (t - 1) for t in types)] + ann + [world.STAGES[k].toughness])
    return out


def stage_asm(built, ids, stage_str_lbl):
    S = ["; generated by tools/mkdata64.py - do not edit", ""]
    S.append("NUM_STAGES = %d" % len(built))
    S.append("NUM_WAVES = %d" % len(world.WAVES1))
    S.append("NUM_SACKS = 5")
    S.append("MAX_LTILES = %d" % max(len(b["lmap"]) for b in built))
    un = unlocks(ids)
    for part in ("tmap", "cmap", "lmap", "sacks", "pg", "pa", "waves"):
        S.append("st_%s_lo .byte %s" % (part, ",".join("<st%d_%s" % (k, part) for k in range(len(built)))))
        S.append("st_%s_hi .byte %s" % (part, ",".join(">st%d_%s" % (k, part) for k in range(len(built)))))
    S.append("st_nltiles .byte %s" % ",".join(str(len(b["lmap"])) for b in built))
    S.append("; the flag: x (two pixel units), y (lines)")
    S.append("st_flag_x .byte %s" % ",".join(str(b["flag"][0]) for b in built))
    S.append("st_flag_y .byte %s" % ",".join(str(b["flag"][1]) for b in built))
    S.append("; defenders (a bit per type), the two lines announcing the new one, toughness")
    for i, nm in enumerate(("unlock", "ann1", "ann2", "tough")):
        S.append("st_%s .byte %s" % (nm, ",".join(str(u[i]) for u in un)))
    for k, b in enumerate(built):
        S.append("")
        S.append("st%d_tmap" % k)
        S += db(b["tmap"], 20)
        S.append("st%d_cmap" % k)
        S += db(b["cmap"], 20)
        S.append("st%d_lmap         ; the tiles it uses" % k)
        S.append("        .word " + ",".join("tiles+%d" % (48 * gi) for gi in b["lmap"]))
        S.append("st%d_sacks        ; col, row, tile with the sack, without" % k)
        S += db(b["sacks"], 20)
        S.append("st%d_pg           ; the ground path: x, y, sub, steps left, then (dx, dy, n)..." % k)
        S += db(b["pg"], 24)
        S.append("st%d_pa           ; the air path" % k)
        S += db(b["pa"], 24)
        S.append("st%d_waves        ; per wave: (type, count, interval)..., 0" % k)
        for w in b["waves"]:
            S += db([v for (t, n, iv) in w for v in (t, n, iv)] + [0], 24)
    S.append("")
    S.append("; the stage's own texts: [stage*6 + text*2 + language]")
    lbls = [stage_str_lbl[(k, sid, lang)] for k in range(len(built))
            for sid in world.STAGE_STRINGS for lang in (0, 1)]
    S.append("st_str_lo .byte " + ",".join("<" + x for x in lbls))
    S.append("st_str_hi .byte " + ",".join(">" + x for x in lbls))
    return S


