def text_data():
    def enc(s):
        out = []
        for n, line in enumerate(s.split("\n")):
            if n:
                out.append(0xFE)
            assert len(line) <= 40, line
            out += font.encode(line)
        return out + [0xFF]

    strings = []
    for sid, en, gr in texts.STRINGS:
        en, gr = C64_TEXT.get(sid, (en, gr))
        strings.append((sid, en, gr))
    strings.append(("T_STORY", texts.wrap(texts.STORY_EN), texts.wrap(texts.STORY_GR)))
    strings += EXTRA_STRINGS
    ids = [sid for sid, _, _ in strings] + list(world.STAGE_STRINGS)
    items, alias, seen = [], [], {}
    for sid, en, gr in strings:
        for lang, t in (("en", en), ("gr", gr if gr is not None else en)):
            lbl = "s%s_%s" % (lang, sid)
            d = tuple(enc(t))
            if d in seen:
                alias.append((lbl, seen[d]))
            else:
                seen[d] = lbl
                items.append([lbl, list(d)])
    stage_lbl = {}
    for k, st in enumerate(world.STAGES):
        for sid in world.STAGE_STRINGS:
            for lang in (0, 1):
                lbl = "sst%d_%s_%d" % (k, sid, lang)
                stage_lbl[(k, sid, lang)] = lbl
                items.append([lbl, enc(st.strings[sid][lang])])
    NG = len(font.GLYPHS)
    raw = sum(len(d) for _, d in items)
    pairs = []
    code = NG
    while code < 0xFE:
        counts = {}
        for _, d in items:
            for a, b in zip(d, d[1:]):
                if a < 0xFE and b < 0xFE:
                    counts[(a, b)] = counts.get((a, b), 0) + 1
        if not counts:
            break
        best, n = max(counts.items(), key=lambda kv: kv[1])
        if n < 3:
            break
        pairs.append(best)
        for it in items:
            d, out, i = it[1], [], 0
            while i < len(d):
                if i + 1 < len(d) and (d[i], d[i + 1]) == best:
                    out.append(code)
                    i += 2
                else:
                    out.append(d[i])
                    i += 1
            it[1] = out
        code += 1
    T = ["; generated by tools/mkdata64.py - do not edit", ""]
    for i, sid in enumerate(ids):
        T.append("%s = %d" % (sid, i))
    T.append("FIRST_STAGE_STR = %d" % ids.index(world.STAGE_STRINGS[0]))
    T.append("NUM_PAIRS = %d" % len(pairs))
    T.append("pair_a")
    T += db([a for a, _ in pairs])
    T.append("pair_b")
    T += db([b for _, b in pairs])
    nres = len(strings)
    for lang in ("en", "gr"):
        T.append("strtab_%s_lo .byte %s" % (lang, ",".join("<s%s_%s" % (lang, s) for s, _, _ in strings)))
        T.append("strtab_%s_hi .byte %s" % (lang, ",".join(">s%s_%s" % (lang, s) for s, _, _ in strings)))
    for a, b in alias:
        T.append("%s = %s" % (a, b))
    for lbl, d in items:
        T.append(lbl)
        T += db(d, 20)
    T.append("name_chars")
    T += db(font.encode(texts.NAME_CHARS))
    T.append("NAME_NCHARS = %d" % len(texts.NAME_CHARS))
    T.append("hs_default            ; 8 x (3 glyphs, score lo, hi)")
    hs = []
    for name, pts in texts.HISCORES:
        hs += font.encode(name) + [pts & 255, pts >> 8]
    T += db(hs, 20)
    packed = sum(len(d) for _, d in items) + 2 * len(pairs)
    print("text: %d bytes raw, %d packed (%d pairs), %d strings" % (raw, packed, len(pairs), nres))
    return T, ids, stage_lbl


