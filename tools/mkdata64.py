def sprite_data():
    """hardware sprites, in the order they go to $d000"""
    A = art
    sprites = [
        ("drone_a", A.DRONE_A), ("drone_b", A.DRONE_B),
        ("guard_a", A.GUARD_A), ("guard_b", A.GUARD_B),
        ("guard_am", art.mirror(A.GUARD_A)), ("guard_bm", art.mirror(A.GUARD_B)),
        ("tank_va", A.TANK_V_A), ("tank_vb", A.TANK_V_B),
        ("tank_la", A.TANK_L_A), ("tank_lb", A.TANK_L_B),
        ("tank_lam", art.mirror(A.TANK_L_A)), ("tank_lbm", art.mirror(A.TANK_L_B)),
        ("spark_a", A.SPARK), ("spark_b", A.SPARK_B), ("puff_a", A.PUFF_A), ("puff_b", A.PUFF_B),
        ("bash_a", A.BASH_A), ("bash_b", A.BASH_B), ("poof_a", A.POOF_A), ("poof_b", A.POOF_B),
        ("boom_a", A.BOOM_A), ("boom_b", A.BOOM_B), ("zap_a", A.ZAP_A),
        ("cursor_ok", A.CURSOR_OK), ("cursor_okb", A.CURSOR_OK_B), ("cursor_bad", A.CURSOR_BAD),
    ]
    own = {"cursor_ok": g.WHITE, "cursor_okb": g.YELLOW, "cursor_bad": g.RED}
    G = ["; hardware sprites, copied to SPRITES at start: 64 bytes each",
         "NUM_SPRITES = %d" % len(sprites), "sprite_data"]
    cols, shown = [], []
    for i, (nm, rows) in enumerate(sprites):
        data, c, sh = g.sprite(rows, own.get(nm))
        G.append("; %d %s" % (i, nm))
        G += db(list(data) + [0], 16)
        cols.append(c)
        shown.append(sh)
    for i, (nm, _) in enumerate(sprites):
        G.append("SPR_%s = %d" % (nm.upper(), i))
    G.append("sprite_colour")
    G += db(cols)
    # drawn into the bitmap when there is no sprite for them (shots.asm): the
    # sprite's own colour shows as the cell's darkest colour or its brightest
    dark = [1 if g.luma(c) < 100 and not nm.startswith("cursor") else 0 for c, (nm, _) in zip(cols, sprites)]
    G.append("spr_dark")
    G += db(dark)
    # per enemy type, direction (down, left, right) and frame
    order = ["drone_a", "drone_b"] * 3 + ["guard_a", "guard_b", "guard_am", "guard_bm", "guard_a", "guard_b",
                                          "tank_va", "tank_vb", "tank_lam", "tank_lbm", "tank_la", "tank_lb"]
    names = [nm for nm, _ in sprites]
    G.append("enemy_frames")
    G += db([names.index(nm) for nm in order])
    # a sheet to look at
    sheet = [[-1] * (14 * len(sprites)) for _ in range(14)]
    for i, sh in enumerate(shown):
        for y, line in enumerate(sh):
            for x, c in enumerate(line):
                sheet[y + 1][i * 14 + x + 1] = c
    g.save_png(sheet, os.path.join(PREVIEW, "sprites.png"), 6, 3)
    return G


