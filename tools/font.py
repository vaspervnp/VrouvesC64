# Greek letters that share a shape with a Latin capital
GREEK_ALIAS = {
    'Α': 'A', 'Β': 'B', 'Ε': 'E', 'Ζ': 'Z', 'Η': 'H', 'Ι': 'I', 'Κ': 'K',
    'Μ': 'M', 'Ν': 'N', 'Ο': 'O', 'Ρ': 'P', 'Τ': 'T', 'Υ': 'Y', 'Χ': 'X',
    'Ά': 'A', 'Έ': 'E', 'Ή': 'H', 'Ί': 'I', 'Ό': 'O', 'Ύ': 'Y', 'Ώ': 'Ω',
    'Ϊ': 'I', 'Ϋ': 'Y',
}

INDEX = {ch: i for i, (ch, _) in enumerate(GLYPHS)}


def glyph_index(ch):
    ch = ch.upper() if ch.isascii() else ch
    if ch in ('ς',):
        ch = 'Σ'
    if not ch.isascii():
        ch = ch.upper()
        ch = GREEK_ALIAS.get(ch, ch)
    if ch not in INDEX:
        raise ValueError("No glyph for %r" % ch)
    return INDEX[ch]


def encode(text):
    return [glyph_index(c) for c in text]


def glyph_rows(i):
    rows = GLYPHS[i][1]
    assert len(rows) == 6 and all(len(r) == 3 for r in rows), GLYPHS[i][0]
    out = []
    for r in rows:
        v = 0
        for c in r:
            v = (v << 1) | (1 if c == '#' else 0)
        out.append(v)
    return out
